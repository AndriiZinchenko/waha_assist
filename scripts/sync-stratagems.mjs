// Regenerate src/data/detachments/* from New Recruit.
//
//   npm run sync:stratagems              rewrite every detachment file
//   npm run sync:stratagems -- --dry-run report what would change, write nothing
//   npm run sync:stratagems -- --headed  watch the browser while it works
//
// Two sources, one output. Every detachment a faction can field, with its
// rules, sits in that faction's catalogue book in New Recruit's library
// (the same BattleScribe data the list builder runs on). The stratagems
// come from New Recruit's "Stratagems" book, which is a supporter feature.
// Both are read through the session saved by `sync:armies -- --login`, so
// this handles no credentials of its own. Only the factions with a roster
// in armies/ are synced.

import { readdir, readFile, unlink, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { launchBrowser } from "./sync-newrecruit.mjs";
import { camelCase, detachmentFromRoster, slugify, toStratagem } from "./lib/stratagems.mjs";
import {
  detachmentsForCatalogue,
  inferFactionId,
  stratagemsForDetachment,
} from "./lib/catalogueDetachments.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ARMIES_DIR = path.join(ROOT, "armies");
const OUT_DIR = path.join(ROOT, "src", "data", "detachments");
const SESSION_FILE = path.join(ROOT, ".newrecruit-session.json");
const BASE = "https://www.newrecruit.eu";
// Only this system is ever read, so nothing from another edition can leak in.
const SYSTEM_SHORT = "wh40k-10e";
const BOOK_NAME = "Stratagems";
const CORE_BOOK_NAME = "Warhammer 40,000 10th Edition";
const KEEP_FILES = new Set(["index.ts", "types.ts"]);

const args = new Set(process.argv.slice(2));
const DRY_RUN = args.has("--dry-run");
const HEADED = args.has("--headed");

const log = (...m) => console.log(...m);

/** Run one of New Recruit's RPC calls in the page, as the signed-in user. */
function rpc(page, method, params = []) {
  return page.evaluate(
    async ({ method, params }) => {
      const send = () =>
        fetch(`/api/rpc?m=${encodeURIComponent(method)}`, {
          method: "POST",
          body: JSON.stringify({ method, params }),
          headers: {
            Accept: "application/json, text/plain, */*",
            "Content-Type": "application/json",
            Authorization: localStorage.getItem("access") || "",
          },
        });
      let res = await send();
      if (res.status === 403 && localStorage.getItem("refresh")) {
        const t = await fetch("/api/token", {
          method: "POST",
          body: JSON.stringify({ token: localStorage.getItem("refresh") }),
          headers: { "Content-Type": "application/json" },
        });
        if (t.ok) {
          localStorage.setItem("access", (await t.json()).token);
          res = await send();
        }
      }
      if (!res.ok) return { __error: `rpc ${method} failed (${res.status})` };
      const body = await res.json();
      if (body && body.obfuscated) return JSON.parse(atob(body.data));
      return body;
    },
    { method, params },
  );
}

function tsString(value) {
  // Bodies are multi-line, so a template literal keeps them readable in the
  // generated file. Escape only what would end it early.
  const escaped = String(value).replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
  return `\`${escaped}\``;
}

function renderFile(detachment) {
  const lines = [];
  lines.push(`import type { DetachmentData } from "./types";`);
  lines.push("");
  lines.push(`// Generated by scripts/sync-stratagems.mjs. Do not edit by hand.`);
  lines.push(`export const ${camelCase(detachment.name)}: DetachmentData = {`);
  lines.push(`  name: ${JSON.stringify(detachment.name)},`);
  lines.push(`  faction: ${JSON.stringify(detachment.faction)},`);
  lines.push(`  rules: [`);
  for (const rule of detachment.rules) {
    lines.push(`    {`);
    lines.push(`      name: ${JSON.stringify(rule.name)},`);
    lines.push(`      text: ${tsString(rule.text)},`);
    lines.push(`    },`);
  }
  lines.push(`  ],`);
  lines.push(`  stratagems: [`);
  for (const s of detachment.stratagems) {
    lines.push(`    {`);
    lines.push(`      name: ${JSON.stringify(s.name)},`);
    lines.push(`      cost: ${s.cost},`);
    if (s.type) lines.push(`      type: ${JSON.stringify(s.type)},`);
    if (s.phase) lines.push(`      phase: ${JSON.stringify(s.phase)},`);
    lines.push(`      text: ${tsString(s.text)},`);
    lines.push(`    },`);
  }
  lines.push(`  ],`);
  lines.push(`};`);
  lines.push("");
  return lines.join("\n");
}

/** @param factions Array of { name, detachments } in catalogue order. */
function renderIndex(factions) {
  const all = factions
    .flatMap((f) => f.detachments)
    .sort((a, b) => a.name.localeCompare(b.name));
  const lines = [];
  lines.push(`import type { DetachmentData } from "./types";`);
  for (const d of all) {
    lines.push(`import { ${camelCase(d.name)} } from "./${slugify(d.name)}";`);
  }
  lines.push("");
  lines.push(`export type { DetachmentData, DetachmentRule, Stratagem } from "./types";`);
  lines.push("");
  lines.push(`// Generated by scripts/sync-stratagems.mjs. Do not edit by hand.`);
  lines.push(`const detachmentsByName: Record<string, DetachmentData> = {`);
  for (const d of all) {
    lines.push(`  [${camelCase(d.name)}.name]: ${camelCase(d.name)},`);
  }
  lines.push(`};`);
  lines.push("");
  lines.push(`// Keyed by the roster's catalogue name, in the catalogue's own order.`);
  lines.push(`const detachmentsByFaction: Record<string, DetachmentData[]> = {`);
  for (const f of factions) {
    lines.push(`  ${JSON.stringify(f.name)}: [`);
    for (const d of f.detachments) lines.push(`    ${camelCase(d.name)},`);
    lines.push(`  ],`);
  }
  lines.push(`};`);
  lines.push("");
  lines.push(`export function getDetachmentData(`);
  lines.push(`  name: string | null | undefined,`);
  lines.push(`): DetachmentData | null {`);
  lines.push(`  if (!name) return null;`);
  lines.push(`  return detachmentsByName[name] ?? null;`);
  lines.push(`}`);
  lines.push("");
  lines.push(`/** Every detachment an army from this catalogue can field. */`);
  lines.push(`export function detachmentsForFaction(`);
  lines.push(`  catalogue: string | null | undefined,`);
  lines.push(`): DetachmentData[] {`);
  lines.push(`  if (!catalogue) return [];`);
  lines.push(`  return detachmentsByFaction[catalogue] ?? [];`);
  lines.push(`}`);
  lines.push("");
  return lines.join("\n");
}

/** The catalogue or game-system root of a book row's content. */
function bookRoot(content) {
  return content.catalogue ?? content.gameSystem ?? null;
}

async function main() {
  if (!existsSync(SESSION_FILE)) {
    console.error("No saved session. Run: npm run sync:armies -- --login");
    process.exit(2);
  }

  // Which factions do the synced armies use, and which detachment does each
  // roster already pick? The latter is only checked, never trusted for text.
  const factionNames = [];
  const rosterPicks = [];
  for (const file of (await readdir(ARMIES_DIR)).filter((f) => f.endsWith(".json"))) {
    const json = JSON.parse(await readFile(path.join(ARMIES_DIR, file), "utf8"));
    const catalogue = json?.roster?.forces?.[0]?.catalogueName;
    if (!catalogue) {
      log(`  skip  ${file}: no catalogue in the roster`);
      continue;
    }
    if (!factionNames.includes(catalogue)) factionNames.push(catalogue);
    const own = detachmentFromRoster(json);
    if (own) rosterPicks.push({ file, catalogue, detachment: own.name });
  }
  log(`Factions in use: ${factionNames.join(", ")}`);
  if (factionNames.length === 0) {
    console.error("No rosters found in armies/. Run sync:armies first.");
    process.exit(1);
  }

  const browser = await launchBrowser(!HEADED);
  const context = await browser.newContext({
    viewport: { width: 1400, height: 900 },
    storageState: SESSION_FILE,
  });
  const page = await context.newPage();

  let stratagems;
  const factions = [];
  try {
    await page.goto(`${BASE}/app/MyLists`, { waitUntil: "domcontentloaded" });
    await page.waitForFunction(() => !!document.querySelector("button"), null, {
      timeout: 60_000,
    });
    if (!(await page.evaluate(() => !!localStorage.getItem("access")))) {
      console.error("Session has expired. Run: npm run sync:armies -- --login");
      process.exit(2);
    }

    const library = await rpc(page, "get_library");
    if (!library || library.__error) {
      throw new Error(library?.__error ?? "get_library returned nothing");
    }
    const systems = library.systems ?? library;
    const system = systems.find((s) => s.short === SYSTEM_SHORT);
    if (!system) throw new Error(`system ${SYSTEM_SHORT} not found`);
    const books = system.books ?? [];

    const bookCache = new Map();
    async function fetchBook(book) {
      if (bookCache.has(book.id)) return bookCache.get(book.id);
      const row = await rpc(page, "books_get_book_row", [
        String(system.id),
        String(book.id),
        book.last_updated,
      ]);
      if (!row || row.__error) throw new Error(row?.__error ?? `fetch of ${book.name} failed`);
      const content = JSON.parse(row.content);
      bookCache.set(book.id, content);
      return content;
    }

    const stratBook = books.find((b) => b.name === BOOK_NAME);
    if (!stratBook) {
      throw new Error(
        `no "${BOOK_NAME}" book for ${system.name}; it is a New Recruit supporter feature`,
      );
    }
    log(`Using ${system.name} -> ${stratBook.name} (v${stratBook.nrversion}, ${stratBook.last_updated})`);
    stratagems = (await fetchBook(stratBook)).data.stratagems ?? [];
    log(`Fetched ${stratagems.length} stratagems.`);

    const coreBook = books.find((b) => b.name === CORE_BOOK_NAME);
    const core = coreBook ? bookRoot(await fetchBook(coreBook)) : null;
    if (!core) log(`  note: no "${CORE_BOOK_NAME}" book; linked core rules will be skipped`);

    /** A catalogue plus everything it links, transitively, in link order. */
    async function catalogueWithLinks(book) {
      const roots = [];
      const seen = new Set();
      async function visit(b) {
        if (seen.has(b.id)) return;
        seen.add(b.id);
        const root = bookRoot(await fetchBook(b));
        if (!root) return;
        roots.push(root);
        for (const link of root.catalogueLinks ?? []) {
          const target =
            books.find((x) => x.bsid === link.targetId) ?? books.find((x) => x.name === link.name);
          if (target) await visit(target);
          else log(`  note: ${b.name} links to unknown catalogue "${link.name}"`);
        }
      }
      await visit(book);
      return roots;
    }

    for (const name of factionNames) {
      const book = books.find((b) => b.name === name);
      if (!book) {
        log(`  skip  ${name}: no such catalogue in the library`);
        continue;
      }
      const [catalogue, ...linked] = await catalogueWithLinks(book);
      if (core) linked.push(core);
      const found = detachmentsForCatalogue({ catalogue, linked });
      const factionId = inferFactionId(stratagems, found.map((d) => d.name));
      log(`${name} (v${book.nrversion}): ${found.length} detachment(s), stratagem faction ${factionId ?? "?"}`);
      // Linked catalogues also carry the detachments of allied factions
      // (Imperial Knights lances, Agents of the Imperium). Every real
      // detachment has stratagems under its faction's code, so one without
      // any belongs to someone else.
      const detachments = [];
      const foreign = [];
      for (const d of found) {
        const mine = stratagemsForDetachment(stratagems, d.name, factionId).map(toStratagem);
        if (mine.length === 0) {
          foreign.push(d.name);
          continue;
        }
        detachments.push({ ...d, faction: name, stratagems: mine });
        log(`    ${d.name}: ${d.rules.length} rule(s), ${mine.length} stratagem(s)`);
      }
      if (foreign.length) log(`    (ignored, no ${factionId ?? "?"} stratagems: ${foreign.join(", ")})`);
      factions.push({ name, detachments });
    }
  } finally {
    await browser.close();
  }

  for (const pick of rosterPicks) {
    const faction = factions.find((f) => f.name === pick.catalogue);
    if (faction && !faction.detachments.some((d) => d.name === pick.detachment)) {
      log(`  warn  ${pick.file} uses "${pick.detachment}", which ${pick.catalogue} does not list`);
    }
  }

  const all = factions.flatMap((f) => f.detachments);
  const stems = new Map();
  for (const d of all) {
    const stem = slugify(d.name);
    if (stems.has(stem) && stems.get(stem) !== d.name) {
      throw new Error(`"${d.name}" and "${stems.get(stem)}" would both be written as ${stem}.ts`);
    }
    stems.set(stem, d.name);
  }
  const stale = (await readdir(OUT_DIR)).filter(
    (f) => f.endsWith(".ts") && !KEEP_FILES.has(f) && !stems.has(f.replace(/\.ts$/, "")),
  );

  if (DRY_RUN) {
    log("");
    log("Dry run, nothing written. Would write:");
    for (const stem of stems.keys()) log(`  src/data/detachments/${stem}.ts`);
    log(`  src/data/detachments/index.ts`);
    if (stale.length) log(`Would delete:\n  ${stale.join("\n  ")}`);
    return;
  }

  for (const d of all) {
    await writeFile(path.join(OUT_DIR, `${slugify(d.name)}.ts`), renderFile(d), "utf8");
  }
  await writeFile(path.join(OUT_DIR, "index.ts"), renderIndex(factions), "utf8");
  for (const f of stale) await unlink(path.join(OUT_DIR, f));

  log("");
  log(`Wrote ${all.length} detachment file(s) plus index.ts.`);
  if (stale.length) log(`Deleted (no longer generated):\n  ${stale.join("\n  ")}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
